#include <string.h>
#include <unistd.h>

static int g_failures = 0;

static void check(int condition, const char *description)
{
    if (!condition) {
        fprintf(stderr, "FAIL: %s\n", description);
        g_failures++;
    }
}

/* Writes `content` (exactly `length` bytes) to a fresh temp file and returns its path via `path`. */
static void write_temp_gcode_bytes(const char *content, size_t length, char *path, size_t path_size)
{
    snprintf(path, path_size, "/tmp/printerctl_gcode_test_XXXXXX");
    int fd = mkstemp(path);
    if (fd < 0) {
        fprintf(stderr, "FAIL: mkstemp() failed for temp G-code fixture\n");
        g_failures++;
        return;
    }

    FILE *file = fdopen(fd, "wb");
    fwrite(content, 1, length, file);
    fclose(file);
}

/* Convenience wrapper for NUL-terminated fixture content. */
static void write_temp_gcode(const char *content, char *path, size_t path_size)
{
    write_temp_gcode_bytes(content, strlen(content), path, path_size);
}

/*
 * Opens `content` as a fixture, reads every command, and asserts the reader
 * terminates with `expected_status` on `expected_error_line` (0 when the
 * failure is not line-specific). Returns the number of commands read before
 * the terminal status. Used for every malformed/unsafe fixture so each test
 * is one call instead of a repeated open/next/close dance.
 */
static uint64_t expect_terminal(const char *content,
                                 bool allow_g28,
                                 printerctl_gcode_status_t expected_status,
                                 uint64_t expected_error_line,
                                 const char *description)
{
    char path[64];
    write_temp_gcode(content, path, sizeof(path));

    printerctl_gcode_reader_t reader;
    printerctl_gcode_error_t error;
    printerctl_gcode_result_t result;

    printerctl_gcode_status_t status =
        printerctl_gcode_reader_open(&reader, path, allow_g28, &error);
    check(status == PRINTERCTL_GCODE_OK, description);
    if (status != PRINTERCTL_GCODE_OK) {
        remove(path);
        return 0;
    }

    uint64_t commands = 0;
    for (;;) {
        status = printerctl_gcode_reader_next(&reader, &result, &error);
        if (status != PRINTERCTL_GCODE_OK) {
            break;
        }
        commands++;
    }

    check(status == expected_status, description);
    check(error.line_number == expected_error_line, description);
    check(error.message[0] != '\0', "terminal error carries a message");

    /* Terminal state replays the same status without touching the file. */
    printerctl_gcode_status_t replay = printerctl_gcode_reader_next(&reader, &result, &error);
    check(replay == expected_status, "terminal status is replayed on the next call");

    printerctl_gcode_reader_close(&reader, &error);
    remove(path);
    return commands;
}

static void test_normal_file(void)
{
    const char *content =
        "; generated by PrusaSlicer\n"
        "\n"
        "G21 ; set units to millimeters\n"
        "G90\n"
        "  M104 S200   \n"
        "(heat up (outer shell)) G1 X10 Y20\n"
        "M105\n";

    char path[64];
    write_temp_gcode(content, path, sizeof(path));

    printerctl_gcode_reader_t reader;
    printerctl_gcode_error_t error;
    printerctl_gcode_result_t result;

    printerctl_gcode_status_t status =
        printerctl_gcode_reader_open(&reader, path, false, &error);
    check(status == PRINTERCTL_GCODE_OK, "normal file opens");
    check(reader.size == strlen(content), "open snapshots the exact file size");

    const char *expected_commands[] = {"G21", "G90", "M104 S200", " G1 X10 Y20", "M105"};
    const uint64_t expected_lines[] = {3, 4, 5, 6, 7};
    /* strip_comments removes the parenthesized comment but keeps the space
     * that followed it; trim only strips line edges. */
    unsigned previous_percent = 0;

    for (size_t i = 0; i < 5; i++) {
        status = printerctl_gcode_reader_next(&reader, &result, &error);
        check(status == PRINTERCTL_GCODE_OK, "normal file yields the expected number of commands");
        if (status != PRINTERCTL_GCODE_OK) {
            break;
        }

        char expected_trimmed[64];
        snprintf(expected_trimmed, sizeof(expected_trimmed), "%s", expected_commands[i]);
        /* expected values above are already trimmed except the deliberate
         * leading space marker; normalize it the same way the reader does. */
        const char *expected = expected_trimmed;
        while (*expected == ' ') {
            expected++;
        }

        check(strcmp(result.command, expected) == 0, "command text is normalized as expected");
        check(result.line_number == expected_lines[i], "command carries its source line number");
        check(result.command_number == i + 1, "command_number is the 1-based ordinal");
        check(result.progress_percent >= previous_percent, "progress percent never decreases");
        check(result.file_size == strlen(content), "result carries the open-time file size");
        previous_percent = result.progress_percent;
    }

    check(result.progress_percent == 100, "last command of the file reports 100%");
    check(result.bytes_consumed == strlen(content), "last command consumed every byte");

    status = printerctl_gcode_reader_next(&reader, &result, &error);
    check(status == PRINTERCTL_GCODE_EOF, "file ends with EOF after the last command");

    status = printerctl_gcode_reader_next(&reader, &result, &error);
    check(status == PRINTERCTL_GCODE_EOF, "EOF is terminal and replayed");

    check(printerctl_gcode_reader_close(&reader, &error) == PRINTERCTL_GCODE_OK, "close succeeds");
    check(printerctl_gcode_reader_close(&reader, &error) == PRINTERCTL_GCODE_OK, "second close is a no-op");

    remove(path);
}

