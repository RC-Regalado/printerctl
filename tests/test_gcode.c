static void test_malformed_lines(void)
{
    expect_terminal("G21\rG90\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 1,
                    "a stray CR (not part of CRLF) is malformed");
    expect_terminal("G\x01 1\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 1,
                    "a control byte is malformed");
    expect_terminal("G21 )\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 1,
                    "an unmatched ')' is malformed");
    expect_terminal("G21 (never closed\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 1,
                    "an unterminated '(' comment is malformed");
    expect_terminal("(((((((((too deep)))))))))\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 1,
                    "comment nesting beyond 8 levels is malformed");
    expect_terminal("G90\nG21\xEF\xBB\xBFG1\n", false, PRINTERCTL_GCODE_ERR_MALFORMED, 2,
                    "a BOM sequence past the start of the file is malformed");
}

static void test_unsafe_g28_blocked_by_default(void)
{
    const char *unsafe_variants[] = {
        "G28\n",
        "g28\n",
        "G 28\n",
        "G028\n",
        "G28 X0 Y0\n",
        "G28.1\n",
        "N10 G28\n",
    };

    for (size_t i = 0; i < sizeof(unsafe_variants) / sizeof(unsafe_variants[0]); i++) {
        uint64_t commands = expect_terminal(unsafe_variants[i], false,
                                             PRINTERCTL_GCODE_ERR_UNSAFE_G28, 1,
                                             "a G28 variant is blocked by default");
        check(commands == 0, "no command is returned before the G28 rejection");
    }

    /* G28 after valid commands still fails, and reports its own line. */
    uint64_t commands = expect_terminal("G21\nG90\nG28\n", false,
                                         PRINTERCTL_GCODE_ERR_UNSAFE_G28, 3,
                                         "a later G28 line is blocked and names its line");
    check(commands == 2, "commands before the G28 line were returned");
}

