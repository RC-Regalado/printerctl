static void test_line_too_long(void)
{
    char *content = malloc(PRINTERCTL_GCODE_LINE_MAX + 3);
    memset(content, 'X', PRINTERCTL_GCODE_LINE_MAX + 1);
    content[PRINTERCTL_GCODE_LINE_MAX + 1] = '\n';
    content[PRINTERCTL_GCODE_LINE_MAX + 2] = '\0';

    char path[64];
    write_temp_gcode(content, path, sizeof(path));
    free(content);

    printerctl_gcode_reader_t reader;
    printerctl_gcode_error_t error;
    printerctl_gcode_result_t result;

    check(printerctl_gcode_reader_open(&reader, path, false, &error) == PRINTERCTL_GCODE_OK,
          "oversized-line file opens");
    check(printerctl_gcode_reader_next(&reader, &result, &error) == PRINTERCTL_GCODE_ERR_LINE_TOO_LONG,
          "a line one byte over the limit is rejected as LINE_TOO_LONG");
    check(error.line_number == 1, "oversized-line error names line 1");
    check(printerctl_gcode_reader_next(&reader, &result, &error) == PRINTERCTL_GCODE_ERR_LINE_TOO_LONG,
          "LINE_TOO_LONG is terminal and replayed");

    printerctl_gcode_reader_close(&reader, &error);
    remove(path);
}

