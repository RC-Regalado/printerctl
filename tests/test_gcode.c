static void test_invalid_arguments_and_not_open(void)
{
    printerctl_gcode_reader_t reader;
    printerctl_gcode_error_t error;
    printerctl_gcode_result_t result;

    check(printerctl_gcode_reader_open(NULL, "x", false, &error) ==
              PRINTERCTL_GCODE_ERR_INVALID_ARGUMENT,
          "open with a NULL reader is rejected");
    check(printerctl_gcode_reader_open(&reader, NULL, false, &error) ==
              PRINTERCTL_GCODE_ERR_INVALID_ARGUMENT,
          "open with a NULL path is rejected");
    check(printerctl_gcode_reader_open(&reader, "x", false, NULL) ==
              PRINTERCTL_GCODE_ERR_INVALID_ARGUMENT,
          "open with a NULL out_error is rejected");

    /* reader was reset to a well-defined not-open state by the NULL-path open. */
    check(printerctl_gcode_reader_next(&reader, &result, &error) ==
              PRINTERCTL_GCODE_ERR_NOT_OPEN,
          "next on a never-opened reader reports NOT_OPEN");
    check(printerctl_gcode_reader_next(NULL, &result, &error) ==
              PRINTERCTL_GCODE_ERR_INVALID_ARGUMENT,
          "next with a NULL reader is rejected");
    check(printerctl_gcode_reader_close(NULL, &error) ==
              PRINTERCTL_GCODE_ERR_INVALID_ARGUMENT,
          "close with a NULL reader is rejected");
    check(printerctl_gcode_reader_close(&reader, &error) == PRINTERCTL_GCODE_OK,
          "close on a never-opened reader is a no-op");
}

