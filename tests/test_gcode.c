static void test_file_changed_underneath_reader(void)
{
    char path[64];
    write_temp_gcode("G21\nG90\nM105\n", path, sizeof(path));

    printerctl_gcode_reader_t reader;
    printerctl_gcode_error_t error;
    printerctl_gcode_result_t result;

    check(printerctl_gcode_reader_open(&reader, path, false, &error) == PRINTERCTL_GCODE_OK,
          "file opens before being modified");
    check(printerctl_gcode_reader_next(&reader, &result, &error) == PRINTERCTL_GCODE_OK,
          "first command reads before the modification");

    /* Grow the file: the size check catches this deterministically,
     * independent of mtime resolution. */
    FILE *rewriter = fopen(path, "a");
    fputs("G1 X0\n", rewriter);
    fclose(rewriter);

    check(printerctl_gcode_reader_next(&reader, &result, &error) ==
              PRINTERCTL_GCODE_ERR_FILE_CHANGED,
          "a file modified underneath the reader fails with FILE_CHANGED");
    check(printerctl_gcode_reader_next(&reader, &result, &error) ==
              PRINTERCTL_GCODE_ERR_FILE_CHANGED,
          "FILE_CHANGED is terminal and replayed");

    printerctl_gcode_reader_close(&reader, &error);
    remove(path);
}

int main(void)
{
    test_normal_file();
    test_empty_file();
    test_comments_and_blank_lines_only();
    test_bom_and_crlf();
    test_final_line_without_newline();
    test_inline_semicolon_inside_parens();
    test_line_too_long();
    test_line_at_exact_limit_is_accepted();
    test_malformed_lines();
    test_unsafe_g28_blocked_by_default();
    test_g28_lookalikes_are_not_blocked();
    test_g28_allowed_when_confirmed();
    test_open_errors();
    test_invalid_arguments_and_not_open();
    test_next_after_close_reports_not_open();
    test_file_changed_underneath_reader();

    if (g_failures > 0) {
        fprintf(stderr, "%d check(s) failed\n", g_failures);
        return EXIT_FAILURE;
    }

    printf("All G-code checks passed\n");
    return EXIT_SUCCESS;
}
