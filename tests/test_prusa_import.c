#define _POSIX_C_SOURCE 200809L

#include "printerctl/config.h"
#include "printerctl/prusa_import.h"

#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

static int g_failures = 0;

static void check(int condition, const char *description)
{
    if (!condition) {
        fprintf(stderr, "FAIL: %s\n", description);
        g_failures++;
    }
}

static bool near(double a, double b)
{
    return fabs(a - b) < 1e-9;
}

static void write_temp(const char *content, char *path, size_t path_size)
{
    snprintf(path, path_size, "/tmp/printerctl_prusa_test_XXXXXX");
    int fd = mkstemp(path);
    if (fd < 0) {
        fprintf(stderr, "FAIL: mkstemp\n");
        exit(1);
    }
    FILE *file = fdopen(fd, "w");
    fputs(content, file);
    fclose(file);
}

static printerctl_prusa_import_status_t import_text(const char *content,
                                                    const printerctl_prusa_import_options_t *opts,
                                                    printerctl_prusa_import_result_t *result,
                                                    printerctl_prusa_import_error_t *error)
{
    char path[64];
    write_temp(content, path, sizeof(path));
    printerctl_prusa_import_options_t defaults;
    printerctl_prusa_import_options_init(&defaults);
    printerctl_prusa_import_status_t status =
        printerctl_prusa_import_file(path, opts != NULL ? opts : &defaults, result, error);
    unlink(path);
    return status;
}

/* Trimmed copy of a real PrusaSlicer 2.9 BIQU B1 printer profile. */
static const char *const k_biqu_ini =
    "# generated by PrusaSlicer 2.9.6 on 2026-10-11 at 13:45:49 UTC\n"
    "autoemit_temperature_commands = 1\n"
    "bed_shape = 0x0,235x0,235x235,0x235\n"
    "end_gcode = ; BIQU Default End Gcode\\n\\nG91 ; Switch to relative positioning\\n\n"
    "gcode_flavor = marlin2\n"
    "machine_limits_usage = time_estimate_only\n"
    "machine_max_feedrate_e = 25,25\n"
    "machine_max_feedrate_x = 150,150\n"
    "machine_max_feedrate_y = 150,150\n"
    "machine_max_feedrate_z = 5,5\n"
    "max_print_height = 270\n"
    "retract_lift = 0\n";

static void test_printer_profile_ini(void)
{
    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    check(import_text(k_biqu_ini, NULL, &result, &error) == PRINTERCTL_PRUSA_IMPORT_OK,
          "BIQU B1 printer profile imports");
    check(!result.from_gcode, "ini source is reported as a printer profile");
    check(near(result.bed_max_x, 235.0) && near(result.bed_max_y, 235.0), "bed box parsed");
    check(near(result.min_x, 30.0) && near(result.max_x, 205.0) && near(result.min_y, 30.0) &&
              near(result.max_y, 205.0),
          "default 30 mm inset applied on every edge");
    check(near(result.safe_z, 5.0), "default safe_z is 5 mm");
    check(near(result.xy_feedrate, 9000.0), "xy feedrate = 60 * min(150, 150)");
    check(near(result.z_feedrate, 300.0), "z feedrate = 60 * machine_max_feedrate_z");
}

/* The configuration block PrusaSlicer appends to sliced ASCII G-code,
 * preceded by body comments that look like key/value pairs. */
static const char *const k_gcode =
    "; generated by PrusaSlicer 2.9.6 on 2026-10-09 at 18:46:24 UTC\n"
    "; external perimeters extrusion width = 0.45mm\n"
    "M104 S200 ; set temperature\n"
    "G1 Z5 F5000 ; lift nozzle\n"
    ";TYPE:Skirt/Brim\n"
    "G1 X38.95 Y15.958 E2.23344\n"
    "; prusaslicer_config = begin\n"
    "; bed_shape = 0x0,100x0,100x100,0x100\n"
    "; machine_max_feedrate_x = 40,30\n"
    "; machine_max_feedrate_y = 40,30\n"
    "; machine_max_feedrate_z = 10,10\n"
    "; travel_speed = 130\n"
    "; travel_speed_z = 0\n"
    "; prusaslicer_config = end\n";

static void test_sliced_gcode_configuration_block(void)
{
    printerctl_prusa_import_options_t options;
    printerctl_prusa_import_options_init(&options);
    options.inset_mm = 10.0;
    options.safe_z_mm = 2.5;
    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    check(import_text(k_gcode, &options, &result, &error) == PRINTERCTL_PRUSA_IMPORT_OK,
          "sliced G-code configuration block imports");
    check(result.from_gcode, "gcode source is reported as a G-code configuration block");
    check(near(result.min_x, 10.0) && near(result.max_x, 90.0), "explicit inset applied");
    check(near(result.safe_z, 2.5), "explicit safe_z applied");
    check(near(result.xy_feedrate, 2400.0),
          "xy feedrate uses the slowest of travel_speed and machine limits");
    check(!result.has_travel_speed_z, "travel_speed_z = 0 is unavailable, not unlimited");
    check(near(result.z_feedrate, 600.0), "z feedrate falls back to machine_max_feedrate_z");
}

static void test_generated_config_round_trips_through_config_loader(void)
{
    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    check(import_text(k_biqu_ini, NULL, &result, &error) == PRINTERCTL_PRUSA_IMPORT_OK,
          "fixture imports for round trip");

    char path[64];
    write_temp("", path, sizeof(path));
    FILE *out = fopen(path, "w");
    check(out != NULL, "open generated config");
    check(printerctl_prusa_import_write_config(&result, "BiquB1.ini", out),
          "generated config is written");
    fclose(out);

    printerctl_config_overrides_t overrides;
    printerctl_config_overrides_init(&overrides);
    printerctl_config_error_t config_error;
    check(printerctl_config_load_file(path, &overrides, &config_error) == PRINTERCTL_CONFIG_OK,
          "generated config is accepted by the printerctl config loader");
    check(overrides.has_calibration_min_x && near(overrides.calibration_min_x, 30.0) &&
              overrides.has_calibration_max_x && near(overrides.calibration_max_x, 205.0) &&
              overrides.has_calibration_min_y && near(overrides.calibration_min_y, 30.0) &&
              overrides.has_calibration_max_y && near(overrides.calibration_max_y, 205.0),
          "calibration bounds survive the round trip");
    check(overrides.has_calibration_safe_z && near(overrides.calibration_safe_z, 5.0) &&
              overrides.has_calibration_xy_feedrate &&
              near(overrides.calibration_xy_feedrate, 9000.0) &&
              overrides.has_calibration_z_feedrate &&
              near(overrides.calibration_z_feedrate, 300.0),
          "calibration motion values survive the round trip");
    check(!overrides.has_port, "no serial port is invented");
    unlink(path);
}

static void expect_failure(const char *content, const printerctl_prusa_import_options_t *opts,
                           printerctl_prusa_import_status_t expected, const char *description)
{
    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    printerctl_prusa_import_status_t status = import_text(content, opts, &result, &error);
    check(status == expected, description);
    check(error.message[0] != '\0', "failure carries a message");
    check(near(result.xy_feedrate, 0.0) && near(result.max_x, 0.0),
          "failed import leaves a zeroed result");
}

static void test_rejections(void)
{
    expect_failure("[printer:BiquB1]\nbed_shape = 0x0,235x0,235x235,0x235\n", NULL,
                   PRINTERCTL_PRUSA_IMPORT_ERR_UNSUPPORTED_FORMAT, "config bundles are rejected");
    expect_failure("GCDE\x01\x00\x00\x00", NULL, PRINTERCTL_PRUSA_IMPORT_ERR_UNSUPPORTED_FORMAT,
                   "binary G-code is rejected");
    expect_failure("machine_max_feedrate_x = 150,150\n", NULL,
                   PRINTERCTL_PRUSA_IMPORT_ERR_MISSING_KEY, "missing bed_shape is rejected");
    expect_failure("bed_shape = 0x0,235x0\nmachine_max_feedrate_x = 150\n"
                   "machine_max_feedrate_z = 5\n",
                   NULL, PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_VALUE,
                   "bed_shape with fewer than three points is rejected");
    expect_failure("bed_shape = 0x0,235x0,235x235,0x235\nmachine_max_feedrate_z = 5\n", NULL,
                   PRINTERCTL_PRUSA_IMPORT_ERR_MISSING_KEY,
                   "missing XY speed sources are rejected");
    expect_failure("bed_shape = 0x0,235x0,235x235,0x235\nmachine_max_feedrate_x = 150\n"
                   "machine_max_feedrate_z = 0,0\n",
                   NULL, PRINTERCTL_PRUSA_IMPORT_ERR_MISSING_KEY,
                   "zero Z machine limit is unavailable, so Z feedrate cannot be derived");
    expect_failure("bed_shape = 0x0,235x0,235x235,0x235\nmachine_max_feedrate_x = fast\n", NULL,
                   PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_VALUE, "non-numeric limits are rejected");

    printerctl_prusa_import_options_t options;
    printerctl_prusa_import_options_init(&options);
    options.inset_mm = 117.5;
    expect_failure(k_biqu_ini, &options, PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_ARGUMENT,
                   "inset leaving no usable area is rejected");
    printerctl_prusa_import_options_init(&options);
    options.inset_mm = -1.0;
    expect_failure(k_biqu_ini, &options, PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_ARGUMENT,
                   "negative inset is rejected");
    printerctl_prusa_import_options_init(&options);
    options.safe_z_mm = 0.0;
    expect_failure(k_biqu_ini, &options, PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_ARGUMENT,
                   "non-positive safe_z is rejected");
    printerctl_prusa_import_options_init(&options);
    options.safe_z_mm = 270.0;
    expect_failure(k_biqu_ini, &options, PRINTERCTL_PRUSA_IMPORT_ERR_INVALID_ARGUMENT,
                   "safe_z at max_print_height is rejected");

    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    printerctl_prusa_import_options_init(&options);
    check(printerctl_prusa_import_file("/nonexistent/printerctl/profile.ini", &options, &result,
                                       &error) == PRINTERCTL_PRUSA_IMPORT_ERR_OPEN,
          "missing file is reported as an open error");
}

static void test_overlong_lines_are_skipped(void)
{
    size_t filler = 10000;
    size_t total = filler + strlen(k_biqu_ini) + 64;
    char *content = malloc(total);
    check(content != NULL, "allocate overlong fixture");
    strcpy(content, "; thumbnail begin ");
    size_t used = strlen(content);
    memset(content + used, 'A', filler);
    used += filler;
    content[used++] = '\n';
    content[used] = '\0';
    strcat(content, k_biqu_ini);

    printerctl_prusa_import_result_t result;
    printerctl_prusa_import_error_t error;
    check(import_text(content, NULL, &result, &error) == PRINTERCTL_PRUSA_IMPORT_OK,
          "keys after an overlong line are still read");
    check(near(result.xy_feedrate, 9000.0), "values after an overlong line are correct");
    free(content);
}

int main(void)
{
    test_printer_profile_ini();
    test_sliced_gcode_configuration_block();
    test_generated_config_round_trips_through_config_loader();
    test_rejections();
    test_overlong_lines_are_skipped();

    if (g_failures != 0) {
        fprintf(stderr, "%d failure(s)\n", g_failures);
        return 1;
    }
    return 0;
}
